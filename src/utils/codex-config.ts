type TomlTable = Record<string, unknown>

export function formatTomlString(value: string): string {
  // JSON escapes are valid TOML basic-string escapes, but JSON leaves DEL raw and TOML forbids it.
  return JSON.stringify(value).replace(/\u007f/g, "\\u007f")
}

export function formatTomlKey(value: string): string {
  if (/^[A-Za-z0-9_-]+$/.test(value)) return value
  return formatTomlString(value)
}

function formatTomlInlineTable(entries: Record<string, string>): string {
  const parts = Object.entries(entries).map(
    ([key, value]) => `${formatTomlKey(key)} = ${formatTomlString(value)}`,
  )
  return `{ ${parts.join(", ")} }`
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value)
}

function requireStringRecord(value: unknown, label: string): Record<string, string> | undefined {
  if (value === undefined || value === null) return undefined
  if (!isPlainObject(value)) throw new Error(`Invalid MCP ${label}: expected an object of strings`)
  for (const [key, entry] of Object.entries(value)) {
    if (key.length === 0) throw new Error(`Invalid MCP ${label}: empty key`)
    if (typeof entry !== "string") throw new Error(`Invalid MCP ${label}.${key}: expected a string`)
  }
  return value as Record<string, string>
}

// Returns the exact table Codex should read back for one server, or null when it has no transport.
export function toCodexMcpTable(name: string, server: ClaudeMcpServer): TomlTable | null {
  if (typeof name !== "string" || name.length === 0) {
    throw new Error("Invalid MCP server name: expected a non-empty string")
  }
  if (!isPlainObject(server)) throw new Error(`Invalid MCP server ${name}: expected an object`)
  const label = `server ${name}`
  if (server.command !== undefined) {
    if (typeof server.command !== "string") throw new Error(`Invalid MCP ${label}.command: expected a string`)
    const table: TomlTable = { command: server.command }
    if (server.args !== undefined && server.args !== null) {
      if (!Array.isArray(server.args) || server.args.some((arg) => typeof arg !== "string")) {
        throw new Error(`Invalid MCP ${label}.args: expected an array of strings`)
      }
      if (server.args.length > 0) table.args = [...server.args]
    }
    const env = requireStringRecord(server.env, `${label}.env`)
    if (env && Object.keys(env).length > 0) table.env = { ...env }
    return table
  }
  if (server.url !== undefined) {
    if (typeof server.url !== "string") throw new Error(`Invalid MCP ${label}.url: expected a string`)
    const table: TomlTable = { url: server.url }
    const headers = requireStringRecord(server.headers, `${label}.headers`)
    if (headers && Object.keys(headers).length > 0) table.http_headers = { ...headers }
    return table
  }
  return null
}

function renderTable(name: string, table: TomlTable): string {
  const key = formatTomlKey(name)
  const lines = [`[mcp_servers.${key}]`]
  if (typeof table.command === "string") {
    lines.push(`command = ${formatTomlString(table.command)}`)
    if (Array.isArray(table.args)) {
      lines.push(`args = [${table.args.map((arg) => formatTomlString(arg as string)).join(", ")}]`)
    }
    if (table.env) {
      lines.push("", `[mcp_servers.${key}.env]`)
      for (const [envKey, value] of Object.entries(table.env as Record<string, string>)) {
        lines.push(`${formatTomlKey(envKey)} = ${formatTomlString(value)}`)
      }
    }
  } else {
    lines.push(`url = ${formatTomlString(table.url as string)}`)
    if (table.http_headers) {
      lines.push(`http_headers = ${formatTomlInlineTable(table.http_headers as Record<string, string>)}`)
    }
  }
  return lines.join("\n")
}

export function renderMcpServerTables(servers: Record<string, TomlTable>): string {
  return Object.entries(servers).map(([name, table]) => renderTable(name, table)).join("\n\n")
}

export function buildCodexMcpTables(servers: Record<string, ClaudeMcpServer>): Record<string, TomlTable> {
  if (!isPlainObject(servers)) throw new Error("Invalid MCP server config: expected an object")
  const tables: Record<string, TomlTable> = {}
  for (const [name, server] of Object.entries(servers)) {
    const table = toCodexMcpTable(name, server)
    if (table) setOwn(tables, name, table)
    else console.warn(`Skipping MCP server ${name}: it has neither command nor url`)
  }
  return tables
}

function blockMarkers(blockId: string): { begin: string; end: string } {
  if (!/^[A-Za-z0-9:._-]+$/.test(blockId)) throw new Error(`Invalid managed block id: ${blockId}`)
  return {
    begin: `# BEGIN WHETSTONE MANAGED: ${blockId}`,
    end: `# END WHETSTONE MANAGED: ${blockId}`,
  }
}

type Region = { start: number; end: number }
type OwnedRegions = { regions: Region[]; ambiguous: string[] }

const MCP_HEADER = /^\[mcp_servers\.(?:[A-Za-z0-9_-]+|"(?:[^"\\]|\\.)*")(\.env)?\]$/
const ANY_HEADER = /^\[\[?[^\]]/
const STRING_VALUE = String.raw`"(?:[^"\\]|\\.)*"`
const ENV_LINE = new RegExp(String.raw`^(?:[A-Za-z0-9_-]+|${STRING_VALUE}) = ${STRING_VALUE}$`)
const SERVER_LINE = new RegExp(
  String.raw`^(?:(?:command|url) = ${STRING_VALUE}|args = \[.*\]|http_headers = \{.*\})$`,
)

// Legacy writers emitted a comment line followed by `[mcp_servers.*]` tables, with no end marker.
// Consume only lines that grammar could have produced; a blank line ends the region unless another
// MCP table header follows it.
function legacyRegionEnd(lines: string[], markerIndex: number): number {
  let index = markerIndex + 1
  let table: "server" | "env" | null = null
  while (index < lines.length) {
    const line = lines[index].trim()
    if (line === "") {
      let next = index
      while (next < lines.length && lines[next].trim() === "") next += 1
      if (next < lines.length && MCP_HEADER.test(lines[next].trim())) {
        index = next
        continue
      }
      return index
    }
    const header = MCP_HEADER.exec(line)
    if (header) {
      table = header[1] ? "env" : "server"
    } else if (!(table === "server" && SERVER_LINE.test(line)) && !(table === "env" && ENV_LINE.test(line))) {
      return index
    }
    index += 1
  }
  return index
}

function mcpHeaderName(header: string): string {
  return Object.keys(mcpServersOf(Bun.TOML.parse(header) as TomlTable))[0]
}

// Legacy writers left no end marker, so a table a user appended after their output is
// indistinguishable from one they wrote. Only tables the incoming set replaces are provably
// safe to drop; everything else stays in place.
function legacyTableRegions(
  lines: string[],
  start: number,
  end: number,
  replaced: ReadonlySet<string>,
  ambiguous: Set<string>,
): Region[] {
  const regions: Region[] = []
  let current: { start: number; owned: boolean } | null = null
  for (let index = start; index <= end; index += 1) {
    const isHeader = index < end && MCP_HEADER.test(lines[index].trim())
    if (index < end && !isHeader) continue
    if (current?.owned) regions.push({ start: current.start, end: index })
    if (index === end) break
    const name = mcpHeaderName(lines[index].trim())
    const owned = replaced.has(name)
    if (!owned) ambiguous.add(name)
    current = { start: index, owned }
  }
  return regions
}

function findOwnedRegions(
  lines: string[],
  blockId: string,
  legacyMarkers: string[],
  replaced: ReadonlySet<string> = new Set(),
): OwnedRegions {
  const { begin, end } = blockMarkers(blockId)
  const regions: Region[] = []
  const ambiguous = new Set<string>()
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index].trim()
    if (line === begin) {
      const close = lines.findIndex((candidate, at) => at > index && candidate.trim() === end)
      const nested = lines.findIndex((candidate, at) => at > index && candidate.trim() === begin)
      if (close === -1 || (nested !== -1 && nested < close)) {
        throw new Error(`Managed block "${blockId}" has no matching end marker; refusing to edit the config`)
      }
      regions.push({ start: index, end: close + 1 })
      index = close
    } else if (line === end) {
      throw new Error(`Managed block "${blockId}" has an end marker without a begin marker; refusing to edit the config`)
    } else if (legacyMarkers.includes(line)) {
      const regionEnd = legacyRegionEnd(lines, index)
      regions.push({ start: index, end: index + 1 })
      regions.push(...legacyTableRegions(lines, index + 1, regionEnd, replaced, ambiguous))
      index = regionEnd - 1
    }
  }
  return { regions, ambiguous: [...ambiguous] }
}

function parseToml(content: string, label: string): TomlTable {
  try {
    return Bun.TOML.parse(content) as TomlTable
  } catch (err) {
    throw new Error(`${label} is not valid TOML (${(err as Error).message}); refusing to edit it`)
  }
}

function mcpServersOf(parsed: TomlTable): TomlTable {
  const value = parsed.mcp_servers
  return isPlainObject(value) ? value : {}
}

export function mergeCodexMcpBlock(
  existing: string,
  blockId: string,
  servers: Record<string, TomlTable>,
  legacyMarkers: string[] = [],
): string {
  const { begin, end } = blockMarkers(blockId)
  const lines = existing.split(/\r?\n/)
  const { regions, ambiguous } = findOwnedRegions(lines, blockId, legacyMarkers, new Set(Object.keys(servers)))
  for (const name of ambiguous) {
    console.warn(
      `Keeping [mcp_servers.${formatTomlKey(name)}] found after a legacy whetstone marker: ` +
        "it may be a stale synced server or one added by hand, so it was not removed. Delete it manually if it is stale.",
    )
  }

  const kept: string[] = []
  let cursor = 0
  let insertAt = -1
  for (const region of regions) {
    kept.push(lines.slice(cursor, region.start).join("\n").trimEnd())
    const ownsTable = lines.slice(region.start, region.end).some((line) => ANY_HEADER.test(line.trim()))
    const firstContent = lines.slice(region.end).find((line) => line.trim() !== "" && !line.trim().startsWith("#"))
    const tailStartsWithTable = firstContent === undefined || ANY_HEADER.test(firstContent.trim())
    if (insertAt === -1 && tailStartsWithTable) insertAt = kept.length
    if (ownsTable && !tailStartsWithTable) {
      throw new Error(
        `Codex config has keys directly after the whetstone-managed MCP section ("${firstContent!.trim()}"). ` +
          "TOML assigns them to the managed table, so they cannot be preserved in place; " +
          "move them above the managed section or under their own table header, then rerun.",
      )
    }
    cursor = region.end
  }
  kept.push(lines.slice(cursor).join("\n"))
  const segments = kept.map((part) => part.replace(/^\n+/, "").trimEnd())
  const joinSegments = (parts: string[]) => parts.filter(Boolean).join("\n\n")
  const userContent = joinSegments(segments)

  const parsedUser = parseToml(userContent, "Existing Codex config")
  if (regions.length > 0) {
    let parsedOriginal: TomlTable | null = null
    try {
      parsedOriginal = Bun.TOML.parse(existing) as TomlTable
    } catch {
      // Legacy writers could leave duplicate tables behind; the stripped content still parses.
    }
    if (parsedOriginal) assertOnlyMcpServersRemoved(parsedOriginal, parsedUser)
  }

  const userServers = mcpServersOf(parsedUser)
  const written: Record<string, TomlTable> = {}
  for (const [name, table] of Object.entries(servers)) {
    if (Object.hasOwn(userServers, name)) {
      console.warn(`Skipping MCP server ${name}: config.toml already defines [mcp_servers.${formatTomlKey(name)}] outside the managed block`)
      continue
    }
    setOwn(written, name, table)
  }

  // An existing block is replaced where it sits; any content after it starts with a table header,
  // so the managed tables cannot absorb user keys.
  let result = userContent
  if (Object.keys(written).length > 0) {
    const block = [begin, renderMcpServerTables(written), end].join("\n")
    result = insertAt === -1
      ? joinSegments([userContent, block])
      : joinSegments([...segments.slice(0, insertAt), block, ...segments.slice(insertAt)])
  }
  if (result) result += "\n"

  const expected: TomlTable = structuredClone(parsedUser)
  if (Object.keys(written).length > 0) {
    expected.mcp_servers = { ...userServers, ...written }
  }
  const parsedResult = parseToml(result, "Merged Codex config")
  if (!Bun.deepEquals(parsedResult, expected, true)) {
    throw new Error("Merged Codex config does not round-trip; refusing to write it")
  }
  return result
}

function assertOnlyMcpServersRemoved(original: TomlTable, stripped: TomlTable): void {
  const { mcp_servers: originalServers, ...originalRest } = original
  const { mcp_servers: strippedServers, ...strippedRest } = stripped
  const before = isPlainObject(originalServers) ? originalServers : {}
  const after = isPlainObject(strippedServers) ? strippedServers : {}
  const unchanged = Bun.deepEquals(originalRest, strippedRest, true)
    && Object.entries(after).every(([name, table]) => Bun.deepEquals(before[name], table, true))
  if (!unchanged) {
    throw new Error("Removing the whetstone-managed MCP section would change other Codex settings; refusing to edit the config")
  }
}

type CodexMcpConfigUpdate = {
  root: string
  configPath: string
  blockId: string
  servers: Record<string, ClaudeMcpServer>
  legacyMarkers: string[]
}

// Validates and merges up front so callers can refuse before writing anything else.
export async function prepareCodexMcpConfig(options: CodexMcpConfigUpdate): Promise<() => Promise<void>> {
  const { root, configPath, blockId, legacyMarkers } = options
  const servers = buildCodexMcpTables(options.servers)
  await assertSafeDestination(root, configPath)

  let existing: string | null = null
  if (await lstatIfExists(configPath)) {
    const handle = await fs.open(configPath, constants.O_RDONLY | constants.O_NOFOLLOW)
    try {
      existing = await handle.readFile("utf8")
    } finally {
      await handle.close()
    }
  }

  const noop = async () => {}
  if (existing === null && Object.keys(servers).length === 0) return noop
  if (existing !== null && Object.keys(servers).length === 0
    && findOwnedRegions(existing.split(/\r?\n/), blockId, legacyMarkers).regions.length === 0) {
    return noop
  }

  const next = mergeCodexMcpBlock(existing ?? "", blockId, servers, legacyMarkers)
  if (next === existing) return () => restrictConfigMode(configPath)

  return async () => {
    if (existing !== null) {
      const backupPath = await backupFile(configPath)
      if (backupPath) console.log(`Backed up existing config to ${backupPath}`)
    }
    await writeText(configPath, next, { root, mode: 0o600 })
  }
}

// The managed block can carry MCP secrets, so tighten an unchanged config the same as a rewritten one.
async function restrictConfigMode(configPath: string): Promise<void> {
  const handle = await fs.open(configPath, constants.O_RDONLY | constants.O_NOFOLLOW)
  try {
    const info = await handle.stat()
    if (!info.isFile()) throw new Error(`Refusing to change mode of non-regular file ${configPath}`)
    if ((info.mode & 0o777) !== 0o600) await handle.chmod(0o600)
  } finally {
    await handle.close()
  }
}
