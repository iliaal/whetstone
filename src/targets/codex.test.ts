import { chmod, mkdir, mkdtemp, readdir, readFile, rm, stat, symlink, writeFile } from "fs/promises"
import os from "os"
import path from "path"
import { afterEach, expect, test } from "bun:test"
import type { CodexBundle } from "../types/codex"
import { syncToCodex } from "../sync/codex"
import { writeCodexBundle } from "./codex"

const tempRoots: string[] = []

afterEach(async () => {
  await Promise.all(tempRoots.splice(0).map((dir) => rm(dir, { recursive: true, force: true })))
})

async function tempRoot(): Promise<string> {
  const root = await mkdtemp(path.join(os.tmpdir(), "whetstone-codex-"))
  tempRoots.push(root)
  return root
}

function bundle(overrides: Partial<CodexBundle> = {}): CodexBundle {
  return {
    pluginName: "demo",
    prompts: [],
    skillDirs: [],
    generatedSkills: [],
    mcpServers: { demo: { command: "node", args: ["server.js"], env: { API_TOKEN: "secret" } } },
    ...overrides,
  }
}

const userSettings = [
  'approval_policy = "untrusted"',
  'sandbox_mode = "read-only"',
  'model = "user-model"',
  "",
  '[projects."/work/demo"]',
  'trust_level = "untrusted"',
  "",
].join("\n")

const userParsed = {
  approval_policy: "untrusted",
  sandbox_mode: "read-only",
  model: "user-model",
  projects: { "/work/demo": { trust_level: "untrusted" } },
}

test("Codex conversion merges MCP servers without dropping user settings", async () => {
  const codexHome = path.join(await tempRoot(), ".codex")
  await mkdir(codexHome)
  const configPath = path.join(codexHome, "config.toml")
  await writeFile(configPath, userSettings)
  await chmod(configPath, 0o644)

  await writeCodexBundle(codexHome, bundle())
  const first = await readFile(configPath, "utf8")
  expect(Bun.TOML.parse(first)).toEqual({
    ...userParsed,
    mcp_servers: { demo: { command: "node", args: ["server.js"], env: { API_TOKEN: "secret" } } },
  })
  expect((await stat(configPath)).mode & 0o777).toBe(0o600)
  const backups = (await readdir(codexHome)).filter((name) => name.startsWith("config.toml.bak."))
  expect(backups).toHaveLength(1)
  expect(await readFile(path.join(codexHome, backups[0]), "utf8")).toBe(userSettings)

  await writeCodexBundle(codexHome, bundle())
  expect(await readFile(configPath, "utf8")).toBe(first)

  await writeCodexBundle(codexHome, bundle({ mcpServers: undefined }))
  expect(Bun.TOML.parse(await readFile(configPath, "utf8"))).toEqual(userParsed)
})

test("Codex conversion creates a 0600 config when none exists", async () => {
  const codexHome = path.join(await tempRoot(), ".codex")
  await writeCodexBundle(codexHome, bundle())
  const configPath = path.join(codexHome, "config.toml")
  expect((await stat(configPath)).mode & 0o777).toBe(0o600)
  expect(Bun.TOML.parse(await readFile(configPath, "utf8"))).toEqual({
    mcp_servers: { demo: { command: "node", args: ["server.js"], env: { API_TOKEN: "secret" } } },
  })
})

test("Codex conversion migrates a legacy generated config and keeps settings added later", async () => {
  const codexHome = path.join(await tempRoot(), ".codex")
  await mkdir(codexHome)
  const configPath = path.join(codexHome, "config.toml")
  await writeFile(configPath, [
    'approval_policy = "untrusted"',
    "# Generated by whetstone",
    "",
    "[mcp_servers.stale]",
    'url = "https://example.com/mcp"',
    'http_headers = { "X-Test" = "demo" }',
    "",
    "[mcp_servers.demo]",
    'command = "old"',
    "",
    "[mcp_servers.demo.env]",
    'API_TOKEN = "old-secret"',
    "",
    '[projects."/work/demo"]',
    'trust_level = "untrusted"',
    "",
  ].join("\n"))

  await writeCodexBundle(codexHome, bundle())

  const updated = await readFile(configPath, "utf8")
  expect(updated).not.toContain("# Generated by whetstone")
  expect(Bun.TOML.parse(updated)).toEqual({
    approval_policy: "untrusted",
    projects: { "/work/demo": { trust_level: "untrusted" } },
    mcp_servers: {
      stale: { url: "https://example.com/mcp", http_headers: { "X-Test": "demo" } },
      demo: { command: "node", args: ["server.js"], env: { API_TOKEN: "secret" } },
    },
  })
})

