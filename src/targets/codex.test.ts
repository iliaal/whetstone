test("Codex conversion refuses a component name that escapes the output root", async () => {
  const root = await tempRoot()
  const codexHome = path.join(root, "home", ".codex")
  const source = path.join(root, "skill")
  await mkdir(source)
  await writeFile(path.join(source, ".bashrc"), "echo owned\n")
  const victim = path.join(root, "home", ".bashrc")
  await mkdir(path.dirname(victim), { recursive: true })
  await writeFile(victim, "original\n")

  await expect(writeCodexBundle(codexHome, bundle({ skillDirs: [{ name: "../..", sourceDir: source }] })))
    .rejects.toThrow("Invalid component name")
  await expect(writeCodexBundle(codexHome, bundle({ generatedSkills: [{ name: "../../x", content: "x" }] })))
    .rejects.toThrow("Invalid component name")
  expect(await readFile(victim, "utf8")).toBe("original\n")
})

test("Codex conversion refuses to write through symlinked destinations", async () => {
  const root = await tempRoot()
  const outside = path.join(root, "outside")
  await mkdir(outside)
  await writeFile(path.join(outside, "secret.toml"), userSettings)

  const configHome = path.join(root, "config-home", ".codex")
  await mkdir(configHome, { recursive: true })
  await symlink(path.join(outside, "secret.toml"), path.join(configHome, "config.toml"))
  await expect(writeCodexBundle(configHome, bundle())).rejects.toThrow("Refusing to write through symlink")
  expect((await readdir(configHome)).filter((name) => name.includes(".bak."))).toEqual([])

  const promptHome = path.join(root, "prompt-home", ".codex")
  await mkdir(promptHome, { recursive: true })
  await symlink(outside, path.join(promptHome, "prompts"))
  await expect(writeCodexBundle(promptHome, bundle({
    mcpServers: undefined,
    prompts: [{ name: "demo", content: "Prompt" }],
  }))).rejects.toThrow("Refusing to write through symlink")

  const skillHome = path.join(root, "skill-home", ".codex")
  await mkdir(path.join(skillHome, "skills", "demo"), { recursive: true })
  await symlink(path.join(outside, "secret.toml"), path.join(skillHome, "skills", "demo", "SKILL.md"))
  await expect(writeCodexBundle(skillHome, bundle({
    mcpServers: undefined,
    generatedSkills: [{ name: "demo", content: "Overwritten" }],
  }))).rejects.toThrow("Refusing to write through symlink")

  expect(await readFile(path.join(outside, "secret.toml"), "utf8")).toBe(userSettings)
  expect(await readdir(outside)).toEqual(["secret.toml"])
})

test("Codex plugin and sync blocks coexist without rewriting each other", async () => {
  const codexHome = path.join(await tempRoot(), ".codex")
  await mkdir(codexHome)
  const configPath = path.join(codexHome, "config.toml")
  await writeFile(configPath, userSettings)

  await writeCodexBundle(codexHome, bundle())
  await syncToCodex({ skills: [], mcpServers: { local: { command: "python" } } }, codexHome)
  const combined = await readFile(configPath, "utf8")
  const backups = (await readdir(codexHome)).filter((name) => name.startsWith("config.toml.bak."))

  await writeCodexBundle(codexHome, bundle())
  await syncToCodex({ skills: [], mcpServers: { local: { command: "python" } } }, codexHome)

  expect(await readFile(configPath, "utf8")).toBe(combined)
  expect((await readdir(codexHome)).filter((name) => name.startsWith("config.toml.bak."))).toEqual(backups)
  expect(Bun.TOML.parse(combined)).toEqual({
    ...userParsed,
    mcp_servers: {
      demo: { command: "node", args: ["server.js"], env: { API_TOKEN: "secret" } },
      local: { command: "python" },
    },
  })
})

test("Codex conversion refuses a symlinked .codex derived inside the output directory", async () => {
  const root = await tempRoot()
  const project = path.join(root, "project")
  const outside = path.join(root, "outside")
  await mkdir(project)
  await mkdir(outside)
  await symlink(outside, path.join(project, ".codex"))

  await expect(writeCodexBundle(project, bundle({
    prompts: [{ name: "demo", content: "Prompt" }],
  }))).rejects.toThrow("Refusing to write through symlink")
  expect(await readdir(outside)).toEqual([])
})

test("Codex conversion writes through an explicit .codex home that is a symlink", async () => {
  const root = await tempRoot()
  const real = path.join(root, "dotfiles", "codex")
  await mkdir(real, { recursive: true })
  const codexHome = path.join(root, ".codex")
  await symlink(real, codexHome)

  await writeCodexBundle(codexHome, bundle({ prompts: [{ name: "demo", content: "Prompt" }] }))

  expect(await readFile(path.join(real, "prompts", "demo.md"), "utf8")).toBe("Prompt\n")
  expect(Bun.TOML.parse(await readFile(path.join(real, "config.toml"), "utf8"))).toEqual({
    mcp_servers: { demo: { command: "node", args: ["server.js"], env: { API_TOKEN: "secret" } } },
  })
})

test("Codex conversion tightens an unchanged config to 0600", async () => {
  const codexHome = path.join(await tempRoot(), ".codex")
  await writeCodexBundle(codexHome, bundle())
  const configPath = path.join(codexHome, "config.toml")
  const written = await readFile(configPath, "utf8")
  await chmod(configPath, 0o644)

  await writeCodexBundle(codexHome, bundle())

  expect(await readFile(configPath, "utf8")).toBe(written)
  expect((await stat(configPath)).mode & 0o777).toBe(0o600)
})
